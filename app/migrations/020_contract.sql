-- Meilenstein 5, Phase 1: Verträge mit Beitragsperioden, Umlage-Anteilen und Vorgängen (ADR-022).
CREATE TABLE contracts (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NULL,
    kind ENUM('versicherung', 'steuer', 'club', 'stellplatz', 'finanzierung', 'sonstiges') NOT NULL,
    provider VARCHAR(120) NOT NULL,
    contract_number VARCHAR(60) NOT NULL DEFAULT '',
    tariff VARCHAR(120) NULL,
    starts_on DATE NULL,
    main_due CHAR(5) NULL,
    notice_months TINYINT UNSIGNED NULL,
    payment_interval ENUM('jaehrlich', 'halbjaehrlich', 'vierteljaehrlich', 'monatlich') NULL,
    ends_on DATE NULL,
    allocation ENUM('gleich', 'km', 'fest') NULL,
    hotline VARCHAR(40) NULL,
    member_number VARCHAR(60) NULL,
    note VARCHAR(200) NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_contracts_garage_status (garage_id, status),
    INDEX idx_contracts_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_contracts_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_contracts_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE contract_terms (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    contract_id INT UNSIGNED NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    amount_cents INT UNSIGNED NOT NULL,
    coverage VARCHAR(120) NULL,
    sf_liability VARCHAR(10) NULL,
    sf_comprehensive VARCHAR(10) NULL,
    type_class_liability TINYINT UNSIGNED NULL,
    type_class_partial TINYINT UNSIGNED NULL,
    type_class_full TINYINT UNSIGNED NULL,
    regional_class TINYINT UNSIGNED NULL,
    declared_km_per_year INT UNSIGNED NULL,
    deductible_note VARCHAR(120) NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_contract_terms_contract (contract_id, status),
    CONSTRAINT fk_contract_terms_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_contract_terms_contract FOREIGN KEY (contract_id) REFERENCES contracts (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE contract_allocations (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    contract_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    share_percent DECIMAL(5,2) NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_contract_allocations_contract (contract_id, status),
    CONSTRAINT fk_contract_allocations_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_contract_allocations_contract FOREIGN KEY (contract_id) REFERENCES contracts (id),
    CONSTRAINT fk_contract_allocations_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE contract_events (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    contract_id INT UNSIGNED NOT NULL,
    kind ENUM('beitragsrechnung', 'aenderung', 'schadenmeldung', 'regulierung', 'rueckstufung', 'kuendigung') NOT NULL,
    occurred_on DATE NOT NULL,
    amount_cents INT NULL,
    event_status ENUM('offen', 'in_bearbeitung', 'erledigt') NOT NULL DEFAULT 'offen',
    claim_number VARCHAR(60) NULL,
    damage_id INT UNSIGNED NULL,
    note VARCHAR(300) NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_contract_events_contract (contract_id, status),
    CONSTRAINT fk_contract_events_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_contract_events_contract FOREIGN KEY (contract_id) REFERENCES contracts (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
