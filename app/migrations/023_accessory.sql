CREATE TABLE accessories (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    category ENUM('traeger', 'kindersitz', 'matten', 'dashcam', 'kabel', 'sonstiges') NOT NULL,
    manufacturer VARCHAR(80) NULL,
    article_number VARCHAR(60) NULL,
    bought_on DATE NULL,
    price_cents INT UNSIGNED NULL,
    warranty_until DATE NULL,
    mount_state ENUM('montiert', 'eingelagert') NULL,
    storage_location VARCHAR(120) NULL,
    goes_with_sale TINYINT(1) NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_accessories_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_accessories_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_accessories_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE permits (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    kind ENUM('umweltplakette', 'critair', 'vignette', 'parkausweis', 'mautbox', 'sonstiges') NOT NULL,
    label VARCHAR(80) NOT NULL,
    number VARCHAR(60) NULL,
    valid_from DATE NULL,
    valid_until DATE NULL,
    price_cents INT UNSIGNED NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_permits_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_permits_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_permits_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
