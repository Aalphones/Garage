CREATE TABLE valuations (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    valued_on DATE NOT NULL,
    kind ENUM('kaufpreis', 'verkaufspreis', 'gutachten', 'haendlerangebot', 'bewertung', 'schaetzung') NOT NULL,
    value_type ENUM('haendlereinkauf', 'privatverkauf', 'haendlerverkauf') NULL,
    amount_cents INT UNSIGNED NOT NULL,
    range_low_cents INT UNSIGNED NULL,
    range_high_cents INT UNSIGNED NULL,
    odometer_km INT UNSIGNED NULL,
    provider VARCHAR(120) NOT NULL DEFAULT '',
    note VARCHAR(200) NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_valuations_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_valuations_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_valuations_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE market_listings (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    url VARCHAR(500) NOT NULL,
    fetched_on DATE NOT NULL,
    price_cents INT UNSIGNED NOT NULL,
    odometer_km INT UNSIGNED NOT NULL,
    first_registration CHAR(7) NOT NULL,
    same_drivetrain TINYINT(1) NOT NULL,
    equipment_note VARCHAR(300) NULL,
    postal_code VARCHAR(10) NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_market_listings_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_market_listings_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_market_listings_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
