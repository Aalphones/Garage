CREATE TABLE damages (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    occurred_on DATE NOT NULL,
    kind ENUM('unfall', 'hagel', 'lack', 'glas', 'vandalismus', 'sonstiges') NOT NULL,
    description VARCHAR(500) NOT NULL,
    odometer_km INT UNSIGNED NULL,
    repaired TINYINT(1) NULL,
    repair_event_id INT UNSIGNED NULL,
    appraisal TINYINT(1) NULL,
    diminished_value_cents INT UNSIGNED NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_damages_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_damages_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE recalls (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    manufacturer_code VARCHAR(40) NOT NULL DEFAULT '',
    kba_reference VARCHAR(40) NOT NULL DEFAULT '',
    title VARCHAR(200) NOT NULL,
    recall_status ENUM('offen', 'erledigt', 'nicht_betroffen') NOT NULL,
    done_on DATE NULL,
    event_id INT UNSIGNED NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_recalls_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_recalls_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
