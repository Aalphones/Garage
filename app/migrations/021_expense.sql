-- Meilenstein 5, Phase 1: sonstige Ausgaben und Tankbuch (ADR-022, ADR-025).
CREATE TABLE expenses (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    spent_on DATE NOT NULL,
    category ENUM('parken', 'waesche', 'pflege', 'maut', 'reifeneinlagerung', 'bussgeld', 'sonstiges') NOT NULL,
    amount_cents INT UNSIGNED NOT NULL,
    spread_months TINYINT UNSIGNED NOT NULL DEFAULT 1,
    note VARCHAR(200) NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_expenses_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_expenses_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_expenses_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE fuel_logs (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    garage_id INT UNSIGNED NOT NULL,
    vehicle_id INT UNSIGNED NOT NULL,
    fueled_on DATE NOT NULL,
    odometer_km INT UNSIGNED NOT NULL,
    liters DECIMAL(6,2) NOT NULL,
    amount_cents INT UNSIGNED NOT NULL,
    is_full TINYINT(1) NOT NULL,
    odometer_reading_id INT UNSIGNED NULL,
    station VARCHAR(80) NULL,
    source ENUM('beleg', 'nutzer', 'recherche', 'agent', 'werkstatt') NOT NULL,
    source_url VARCHAR(500) NULL,
    source_document_id INT UNSIGNED NULL,
    confidence ENUM('bestaetigt', 'wahrscheinlich', 'unsicher') NOT NULL,
    status ENUM('aktiv', 'geloescht') NOT NULL DEFAULT 'aktiv',
    status_reason VARCHAR(300) NULL,
    actor VARCHAR(160) NOT NULL,
    user_id INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    INDEX idx_fuel_logs_vehicle_status (vehicle_id, status),
    CONSTRAINT fk_fuel_logs_garage FOREIGN KEY (garage_id) REFERENCES garages (id),
    CONSTRAINT fk_fuel_logs_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
